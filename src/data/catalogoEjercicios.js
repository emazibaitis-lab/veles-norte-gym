// Catálogo general para explorar ejercicios, independiente de las rutinas asignadas.
// Cada ejercicio puede aparecer en más de una zona sin duplicar sus datos.
function crearId(nombre) {
  return nombre
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
}

